function save_action = save_srir_experiment_csv(evaluation_table, experiment_config, csv_file)
%SAVE_SRIR_EXPERIMENT_CSV Append one SRIR experiment to a compact CSV table.
%   The row stores eight experiment settings and all metrics for the original,
%   baseline, proposed, and target responses.

    config_table = create_configuration_table(experiment_config);
    evaluation_row = flatten_evaluation_table(evaluation_table);
    record_table = [config_table, evaluation_row];

    csv_directory = string(fileparts(csv_file));
    if strlength(csv_directory) > 0 && ~isfolder(csv_directory)
        mkdir(csv_directory);
    end

    if ~isfile(csv_file)
        writetable(record_table, csv_file);
        save_action = "created";
        return
    end

    writetable( ...
        record_table, ...
        csv_file, ...
        'WriteMode', ...
        'append', ...
        'WriteVariableNames', ...
        false);
    save_action = "appended";
end


function config_table = create_configuration_table(experiment_config)
%CREATE_CONFIGURATION_TABLE Put the selected experiment settings into one row.

    config_names = [ ...
        "OriginalIndex", ...
        "TargetIndex", ...
        "ProposedResidualScaleMode", ...
        "ProposedResidualScaleGain", ...
        "ProposedZoomEnabled", ...
        "ProposedZoomPreserveOmniRMS", ...
        "ProposedZoomDepthCoeff", ...
        "ProposedZoomDistance_m"];

    config_table = table( ...
        double(experiment_config.OriginalIndex), ...
        double(experiment_config.TargetIndex), ...
        string(experiment_config.ProposedResidualScaleMode), ...
        double(experiment_config.ProposedResidualScaleGain), ...
        logical(experiment_config.ProposedZoomEnabled), ...
        logical(experiment_config.ProposedZoomPreserveOmniRMS), ...
        double(experiment_config.ProposedZoomDepthCoeff), ...
        double(experiment_config.ProposedZoomDistance_m), ...
        'VariableNames', ...
        cellstr(config_names));
end


function evaluation_row = flatten_evaluation_table(evaluation_table)
%FLATTEN_EVALUATION_TABLE Spread response metrics across one CSV row.

    response_names = ["Original", "Baseline", "Proposed", "Target"];
    metric_names = [ ...
        "RMS_dB", ...
        "IntegratedLoudness_LUFS", ...
        "WaveformErrorToTarget_dB", ...
        "PBC2ToTarget", ...
        "C50_dB", ...
        "DRR_dB", ...
        "T60_s", ...
        "T60Fit_R2", ...
        "T60FitRange", ...
        "EDCSimilarityRMSE_dB", ...
        "DirectArrival_ms"];
    evaluation_row = table();
    for response_idx = 1:numel(response_names)
        response_name = response_names(response_idx);
        for metric_idx = 1:numel(metric_names)
            metric_name = metric_names(metric_idx);
            output_name = response_name + "_" + metric_name;
            evaluation_row.(output_name) = evaluation_table.(metric_name)(response_idx,:);
        end
    end
end
